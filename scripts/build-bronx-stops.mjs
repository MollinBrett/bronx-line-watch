// Builds src/bronx-stops.ts from the MTA's own station list, so nobody types stop IDs by hand.
//
//   node scripts/build-bronx-stops.mjs
//
// Source: data/gtfs/mta-subway-stations.csv, the "MTA Subway Stations" dataset from New York
// State open data (data.ny.gov, dataset 39hk-dx4f), saved as CSV. To refresh it, download the
// dataset again over the old file, run this script, and review the diff of src/bronx-stops.ts.
// test/bronx-stops.test.ts fails if the two ever disagree.
//
// This script reads one file and writes one file. It makes no network calls.
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "data/gtfs/mta-subway-stations.csv";
const OUT = "src/bronx-stops.ts";

/** Minimal CSV reader: handles quoted fields with commas and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((f) => f !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const [header, ...rows] = parseCsv(readFileSync(SOURCE, "utf8"));
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error(`${SOURCE} has no "${name}" column - did the MTA change the file?`);
  return i;
};
const [stopId, complexId, name, borough, routes] = ["GTFS Stop ID", "Complex ID", "Stop Name", "Borough", "Daytime Routes"].map(col);

const bronx = rows
  .filter((r) => r[borough] === "Bx")
  .map((r) => ({ stopId: r[stopId], complexId: r[complexId], name: r[name], routes: r[routes].split(/\s+/).filter(Boolean) }))
  .sort((a, b) => a.stopId.localeCompare(b.stopId));
if (bronx.length < 60) throw new Error(`Only ${bronx.length} Bronx stations found - refusing to write a short list`);

const lines = bronx.map(
  (s) => `  { stopId: ${JSON.stringify(s.stopId)}, complexId: ${JSON.stringify(s.complexId)}, name: ${JSON.stringify(s.name)}, routes: ${JSON.stringify(s.routes)} },`,
);
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-bronx-stops.mjs - do not edit by hand.
//
// Every subway station in the Bronx, from the MTA's own station list
// (${SOURCE}: the "MTA Subway Stations" open-data file, rows where
// Borough is "Bx"). To update: replace that file, run the script, review the diff.
//
// - stopId is the GTFS parent station ID ("401"), the form alerts use. Platform IDs
//   ("401N", "401S") are normalized to it in src/mta.ts.
// - complexId groups platforms that are one station to a rider: 149 St-Hostos on the
//   [2][5] and on the [4] share a complex, and so do the two 161 St-Yankee Stadium stops.
// - routes are the MTA's daytime routes for the stop.

export interface BronxStation {
  stopId: string;
  complexId: string;
  /** The name exactly as the MTA writes it. */
  name: string;
  routes: readonly string[];
}

export const BRONX_STATIONS: readonly BronxStation[] = [
${lines.join("\n")}
];

/** Parent stop IDs of every Bronx station. */
export const BRONX_STOP_IDS: ReadonlySet<string> = new Set(BRONX_STATIONS.map((s) => s.stopId));
`,
);
console.log(`Wrote ${bronx.length} Bronx stations to ${OUT}`);
